"""Collect model facts from config.json + tokenizer + hub metadata. NO weights are downloaded."""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from huggingface_hub import HfApi, hf_hub_download

from trialmatch.model.measure import CANDIDATES, estimate_params_from_config
from trialmatch.utils.common import resolve

OUT_JSON, OUT_MD = "results/metrics/model_facts.json", "docs/model_facts.md"


def _err(e: Exception) -> str:
    return f"{type(e).__name__}: {str(e).splitlines()[0][:200]}"


def facts_for(role: str, repo: str) -> dict:
    rec = {"role": role, "repo": repo, "status": "ok"}
    try:
        cfg = json.loads(Path(hf_hub_download(repo, "config.json")).read_text(encoding="utf-8"))
    except Exception as e:  # gated / offline / missing: skip gracefully
        rec.update(status="inaccessible", error=_err(e))
        return rec
    nh = cfg["num_attention_heads"]
    rec.update(
        layers=cfg["num_hidden_layers"], hidden_size=cfg["hidden_size"], query_heads=nh,
        kv_heads=cfg.get("num_key_value_heads", nh),
        head_dim=cfg.get("head_dim") or cfg["hidden_size"] // nh,
        intermediate_size=cfg.get("intermediate_size"),
        vocab_size_config=cfg["vocab_size"], max_context=cfg.get("max_position_embeddings"),
        tie_word_embeddings=cfg.get("tie_word_embeddings", False),
        rope_theta=cfg.get("rope_theta"), rope_scaling=cfg.get("rope_scaling"),
        rope_parameters=cfg.get("rope_parameters"),
        torch_dtype=cfg.get("torch_dtype", cfg.get("dtype")),
        sliding_window=cfg.get("sliding_window"), use_sliding_window=cfg.get("use_sliding_window"),
    )
    try:
        from transformers import AutoTokenizer
        rec["vocab_size_tokenizer"] = len(AutoTokenizer.from_pretrained(repo))
    except Exception as e:
        rec["vocab_size_tokenizer"], rec["tokenizer_error"] = None, _err(e)
    total = None
    try:
        info = HfApi().model_info(repo)
        total = getattr(info.safetensors, "total", None) if info.safetensors else None
        rec["license"] = (info.card_data.get("license") if info.card_data else None) or \
            next((t.split(":", 1)[1] for t in info.tags if t.startswith("license:")), None)
    except Exception as e:
        rec["license"], rec["model_info_error"] = None, _err(e)
    if total:
        rec["params"], rec["params_source"] = int(total), "hub safetensors metadata"
    else:
        rec["params"], rec["params_source"] = estimate_params_from_config(cfg), "ESTIMATED from config"
    return rec


def to_markdown(recs: list[dict]) -> str:
    cols = ["role", "repo", "params_b", "layers", "hidden_size", "query_heads", "kv_heads", "head_dim",
            "vocab_size_config", "vocab_size_tokenizer", "max_context", "tie_word_embeddings", "license"]
    lines = ["# Model facts", "",
             "Generated by `scripts/model_facts.py` from `config.json`, the tokenizer and hub metadata. "
             "No weights were downloaded. Parameter counts come from hub safetensors metadata when "
             "available, otherwise they are estimates from config.", "",
             "| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for r in recs:
        if r["status"] != "ok":
            lines.append(f"| {r['role']} | {r['repo']} | **inaccessible** ({r['error']}) |" + " |" * (len(cols) - 3))
            continue
        tag = "" if r["params_source"].startswith("hub") else " (est.)"
        row = dict(r, params_b=f"{r['params'] / 1e9:.2f}{tag}")
        lines.append("| " + " | ".join(str(row.get(c)) for c in cols) + " |")
    lines += ["", "## RoPE and other settings", ""]
    for r in recs:
        if r["status"] == "ok":
            rope = r["rope_parameters"] or {"rope_theta": r["rope_theta"], "rope_scaling": r["rope_scaling"]}
            lines.append(f"- **{r['repo']}**: rope={json.dumps(rope)}, dtype={r['torch_dtype']}, "
                         f"sliding_window={r['sliding_window']}, params source: {r['params_source']}")
    return "\n".join(lines) + "\n"


def main():
    recs = [facts_for(role, repo) for role, repo in CANDIDATES.items()]
    resolve(OUT_JSON).write_text(json.dumps(recs, indent=2), encoding="utf-8")
    md = to_markdown(recs)
    resolve(OUT_MD).write_text(md, encoding="utf-8")
    print(md)


if __name__ == "__main__":
    main()
