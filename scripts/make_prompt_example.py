"""Render one TRAIN-split prompt/target pair to docs/prompt_example.md (never uses val/test rows)."""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import pandas as pd

from trialmatch.model.prompt import example_from_row, parse_gold_evidence
from trialmatch.utils.common import load_config, resolve


def main():
    cfg = load_config()
    c = cfg["columns"]
    df = pd.read_parquet(resolve(cfg["paths"]["processed_dir"]) / "train.parquet")
    df = df[(df[c["criterion_type"]] == "inclusion") & df[c["criterion_text"]].notna()]
    row = next(r for _, r in df.iterrows() if len(parse_gold_evidence(r[c["evidence"]])) >= 2)
    ex = example_from_row(row.to_dict())
    md = (f"# Example prompt and target\n\nTrain split, annotation_id {row[c['id']]}. "
          "Generated by `scripts/make_prompt_example.py`.\n\n"
          f"## Prompt\n\n```text\n{ex.prompt}\n```\n\n## Target\n\n```json\n{ex.target}\n```\n")
    resolve("docs/prompt_example.md").write_text(md, encoding="utf-8")
    print("wrote docs/prompt_example.md")


if __name__ == "__main__":
    main()
