"""Full label tables (inclusion/exclusion x overall/train/val/test) with sum checks."""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import pandas as pd

from trialmatch.utils.common import load_config, resolve


def main():
    cfg = load_config()
    c = cfg["columns"]
    proc = resolve(cfg["paths"]["processed_dir"])
    dfs = {n: pd.read_parquet(proc / f"{n}.parquet") for n in ("train", "val", "test")}
    dfs = {"overall": pd.concat(dfs.values(), ignore_index=True), **dfs}
    out, md = {}, ["# Label distribution", "", "Auto-generated by `scripts/label_distribution.py`.", ""]
    for name, d in dfs.items():
        out[name] = {"rows": len(d)}
        md += [f"## {name} ({len(d)} rows)", ""]
        for t, g in d.groupby(c["criterion_type"]):
            vc = g[c["label"]].value_counts()
            assert vc.sum() == len(g), "label counts must sum to row count"
            out[name][t] = {"rows": len(g), "sum_check": int(vc.sum()) == len(g),
                            "labels": {k: {"count": int(v), "pct": round(100 * v / len(g), 2)} for k, v in vc.items()}}
            md += [f"### {t} ({len(g)} rows; counts sum to {int(vc.sum())})", "", "| label | count | % |", "|---|---|---|"]
            md += [f"| `{k}` | {v} | {100 * v / len(g):.2f} |" for k, v in vc.items()] + [""]
        assert sum(out[name][t]["rows"] for t in ("inclusion", "exclusion")) == len(d)
    jp = resolve("results/metrics/label_distribution.json")
    jp.write_text(json.dumps(out, indent=2), encoding="utf-8")
    resolve("docs/label_distribution.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
